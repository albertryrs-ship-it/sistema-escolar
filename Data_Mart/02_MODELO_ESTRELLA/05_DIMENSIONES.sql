-- ==============================================================
-- SECCIÓN 5: DIMENSIONES
-- Descripción: Las 5 dimensiones del modelo estrella (DIM_TIEMPO viene de 01_CALENDARIO.sql).
--   Se crean solo si no existen: el data mart no borra tablas ni datos. Si ya existen, se comprueba
--   que tengan las columnas esperadas; si no, se detiene (error -20114) y el cambio se hace con ALTER TABLE.
-- ==============================================================

-- Se ejecuta desde INSTALAR_MODELO_ESTRELLA.sql, que fija las opciones de la sesión.
-- Sin nombres de estudiantes: el staging del equipo no los copia (datos personales).

-- === DIM_ESTUDIANTE ===
DECLARE n NUMBER; BEGIN
  SELECT COUNT(*) INTO n FROM user_tables WHERE table_name = 'DIM_ESTUDIANTE';
  IF n = 0 THEN
    EXECUTE IMMEDIATE q'~CREATE TABLE dim_estudiante (
    sk_estudiante       NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY,
    id_estudiante       NUMBER(10,0)       NOT NULL,
    nie                 VARCHAR2(30 CHAR)  NOT NULL,
    sexo                VARCHAR2(30 CHAR),
    fecha_nacimiento    DATE               NOT NULL,
    edad                NUMBER(3,0)        NOT NULL,
    tipo_estudiante     VARCHAR2(30 CHAR)  NOT NULL,
    institucion_actual  VARCHAR2(150 CHAR),
    zona_actual         VARCHAR2(150 CHAR),
    departamento_actual VARCHAR2(150 CHAR),
    fecha_actualizacion TIMESTAMP(6)       NOT NULL,
    CONSTRAINT pk_dim_estudiante PRIMARY KEY (sk_estudiante),
    CONSTRAINT uk_dim_estudiante_id UNIQUE (id_estudiante),
    CONSTRAINT chk_dim_estudiante_sexo CHECK (sexo IN ('M', 'F', 'OTRO')),
    CONSTRAINT chk_dim_estudiante_tipo CHECK (tipo_estudiante IN
        ('ACTIVO', 'GRADUADO', 'RETIRADO', 'NO CONTINUO', 'SIN INSCRIPCION'))
)~';
  END IF;
END;
