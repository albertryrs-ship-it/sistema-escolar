-- === Estructura esperada de las dimensiones ===
-- Si las tablas ya existían, deben tener la estructura esperada: el script no borra tablas ni datos.
-- Un cambio de estructura se migra con ALTER TABLE.
DECLARE
  PROCEDURE comprobar(p_tabla VARCHAR2, p_cols VARCHAR2) IS v VARCHAR2(4000); BEGIN
    SELECT LISTAGG(column_name, ',') WITHIN GROUP (ORDER BY column_id) INTO v FROM user_tab_columns WHERE table_name = p_tabla;
    IF v IS NULL OR v <> p_cols THEN
      RAISE_APPLICATION_ERROR(-20114, 'Estructura distinta en '||p_tabla||'. Migrar con ALTER TABLE; el data mart no borra tablas.');
    END IF;
  END;
BEGIN
  comprobar('DIM_ESTUDIANTE', 'SK_ESTUDIANTE,ID_ESTUDIANTE,NIE,SEXO,FECHA_NACIMIENTO,EDAD,TIPO_ESTUDIANTE,INSTITUCION_ACTUAL,ZONA_ACTUAL,DEPARTAMENTO_ACTUAL,FECHA_ACTUALIZACION');
  comprobar('DIM_DOCENTE', 'SK_DOCENTE,ID_DOCENTE,NOMBRE_COMPLETO,ESPECIALIDAD,ANIOS_EXPERIENCIA,INSTITUCION,ACTIVO,FECHA_ACTUALIZACION');
  comprobar('DIM_ASIGNATURA', 'SK_ASIGNATURA,ID_ASIGNATURA,CODIGO,NOMBRE,AREA_CONOCIMIENTO,NIVEL,TIPO_RESULTADO,FECHA_ACTUALIZACION');
  comprobar('DIM_MODALIDAD', 'SK_MODALIDAD,ID_MODALIDAD,TIPO_MODALIDAD,DESCRIPCION,FECHA_ACTUALIZACION');
  comprobar('DIM_CURSO', 'SK_CURSO,ID_CURSO,CODIGO,NOMBRE,SECCION,ANIO,CICLO,GRADO,ORDEN_GRADO,NIVEL,JORNADA,MODALIDAD,INSTITUCION,CODIGO_INSTITUCION,TIPO_INSTITUCION,ZONA,DEPARTAMENTO,CODIGO_ISO,CAPACIDAD_MAXIMA,FECHA_ACTUALIZACION');
END;
