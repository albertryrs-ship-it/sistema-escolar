-- === HECHOS_RESULTADOS ===
DECLARE n NUMBER; BEGIN
  SELECT COUNT(*) INTO n FROM user_tables WHERE table_name = 'HECHOS_RESULTADOS';
  IF n = 0 THEN
    EXECUTE IMMEDIATE q'~CREATE TABLE hechos_resultados (
    id_hecho                      NUMBER(12,0) GENERATED BY DEFAULT AS IDENTITY,
    id_resultado_origen           NUMBER(10,0)      NOT NULL,
    sk_estudiante                 NUMBER(10,0)      NOT NULL,
    sk_docente                    NUMBER(10,0)      NOT NULL,
    sk_asignatura                 NUMBER(10,0)      NOT NULL,
    sk_curso                      NUMBER(10,0)      NOT NULL,
    sk_modalidad                  NUMBER(10,0)      NOT NULL,
    id_tiempo                     NUMBER(8,0)       NOT NULL,
    id_periodo                    NUMBER(10,0)      NOT NULL,
    anio                          NUMBER(4,0)       NOT NULL,
    periodo_numero                NUMBER(1,0)       NOT NULL,
    nota                          NUMBER(5,2),
    resultado_cualitativo         VARCHAR2(100 CHAR),
    peso                          NUMBER            NOT NULL,
    aprobado                      NUMBER(1),
    tipo_intento                  VARCHAR2(30 CHAR) NOT NULL,
    criterio                      VARCHAR2(30 CHAR) NOT NULL,
    sesiones_aplicables           NUMBER(6,0)       NOT NULL,
    sesiones_registradas          NUMBER(6,0)       NOT NULL,
    presencias                    NUMBER(6,0)       NOT NULL,
    asistencia_pct                NUMBER(5,2),
    promedio_periodo_estudiante   NUMBER(5,2),
    asistencia_periodo_estudiante NUMBER(5,2),
    en_riesgo                     NUMBER(1),
    promedio_anual_materia        NUMBER(5,2),
    cobertura_anual_pct           NUMBER(5,2),
    promedio_curso                NUMBER(5,2),
    percentil_curso               NUMBER(5,4),
    cuartil_curso                 NUMBER(1,0),
    nota_anio_anterior            NUMBER(5,2),
    variacion_interanual          NUMBER(6,2),
    beca_vigente                  NUMBER(1)         NOT NULL,
    id_ejecucion                  NUMBER(10,0)      NOT NULL,
    fecha_carga                   TIMESTAMP(6)      NOT NULL,
    CONSTRAINT pk_hechos_resultados PRIMARY KEY (id_hecho),
    CONSTRAINT uk_hechos_resultados_origen UNIQUE (id_resultado_origen),
    CONSTRAINT fk_hechos_estudiante FOREIGN KEY (sk_estudiante) REFERENCES dim_estudiante (sk_estudiante),
    CONSTRAINT fk_hechos_docente    FOREIGN KEY (sk_docente)    REFERENCES dim_docente (sk_docente),
    CONSTRAINT fk_hechos_asignatura FOREIGN KEY (sk_asignatura) REFERENCES dim_asignatura (sk_asignatura),
    CONSTRAINT fk_hechos_curso      FOREIGN KEY (sk_curso)      REFERENCES dim_curso (sk_curso),
    CONSTRAINT fk_hechos_modalidad  FOREIGN KEY (sk_modalidad)  REFERENCES dim_modalidad (sk_modalidad),
    CONSTRAINT fk_hechos_tiempo     FOREIGN KEY (id_tiempo)     REFERENCES dim_tiempo (id_tiempo),
    CONSTRAINT chk_hechos_nota      CHECK (nota BETWEEN 0 AND 100),
    CONSTRAINT chk_hechos_resultado CHECK ((nota IS NULL AND resultado_cualitativo IS NOT NULL)
                                        OR (nota IS NOT NULL AND resultado_cualitativo IS NULL)),
    CONSTRAINT chk_hechos_aprobado  CHECK (aprobado IN (0, 1)),
    CONSTRAINT chk_hechos_riesgo    CHECK (en_riesgo IN (0, 1)),
    CONSTRAINT chk_hechos_beca      CHECK (beca_vigente IN (0, 1)),
    CONSTRAINT chk_hechos_cuartil   CHECK (cuartil_curso BETWEEN 1 AND 4),
    CONSTRAINT chk_hechos_periodo   CHECK (periodo_numero BETWEEN 1 AND 4),
    CONSTRAINT chk_hechos_sesiones  CHECK (sesiones_registradas <= sesiones_aplicables
                                       AND presencias <= sesiones_registradas)
)~';
  END IF;
END;
/

-- === Estructura esperada ===
-- Si las tablas ya existían, deben tener la estructura esperada: el script no borra tablas ni datos.
-- Un cambio de estructura se migra con ALTER TABLE.
DECLARE
  PROCEDURE comprobar(p_tabla VARCHAR2, p_cols VARCHAR2) IS v VARCHAR2(4000); BEGIN
    SELECT LISTAGG(column_name, ',') WITHIN GROUP (ORDER BY column_id) INTO v FROM user_tab_columns WHERE table_name = p_tabla;
    IF v IS NULL OR v <> p_cols THEN
      RAISE_APPLICATION_ERROR(-20114, 'Estructura distinta en '||p_tabla||'. Migrar con ALTER TABLE; el data mart no borra tablas.');
    END IF;
  END;
BEGIN
  comprobar('HECHOS_RESULTADOS', 'ID_HECHO,ID_RESULTADO_ORIGEN,SK_ESTUDIANTE,SK_DOCENTE,SK_ASIGNATURA,SK_CURSO,SK_MODALIDAD,ID_TIEMPO,ID_PERIODO,ANIO,PERIODO_NUMERO,NOTA,RESULTADO_CUALITATIVO,PESO,APROBADO,TIPO_INTENTO,CRITERIO,SESIONES_APLICABLES,SESIONES_REGISTRADAS,PRESENCIAS,ASISTENCIA_PCT,PROMEDIO_PERIODO_ESTUDIANTE,ASISTENCIA_PERIODO_ESTUDIANTE,EN_RIESGO,PROMEDIO_ANUAL_MATERIA,COBERTURA_ANUAL_PCT,PROMEDIO_CURSO,PERCENTIL_CURSO,CUARTIL_CURSO,NOTA_ANIO_ANTERIOR,VARIACION_INTERANUAL,BECA_VIGENTE,ID_EJECUCION,FECHA_CARGA');
END;
